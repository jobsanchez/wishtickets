#!/usr/bin/env node
/**
 * Generates supabase/seed-psgc.sql from philippine-location-json-for-geer.
 * Run: npm run generate:psgc-seed
 */

const fs = require("fs");
const path = require("path");
const loc = require("philippine-location-json-for-geer");

const OUT_PATH = path.join(__dirname, "..", "supabase", "seed-psgc.sql");

// Build province list: use raw provinces, consolidate NCR into "Metro Manila"
const ncrRegCode = "13";
const provinces = [];
const provinceByCode = new Map(); // prov_code -> province key for lookup

// First pass: add Metro Manila for NCR, then non-NCR provinces
let metroManilaKey = null;
for (const p of loc.provinces || []) {
  const name = formatName(p.name);
  if (p.reg_code === ncrRegCode) {
    if (!metroManilaKey) {
      metroManilaKey = "p-ncr";
      provinces.push({ key: metroManilaKey, name: "Metro Manila", code: "NCR" });
    }
    provinceByCode.set(p.prov_code, metroManilaKey);
  } else {
    const key = `p-${p.prov_code}`;
    provinces.push({ key, name, code: p.prov_code });
    provinceByCode.set(p.prov_code, key);
  }
}

// Build city list: map to province key
const cities = [];
for (const c of loc.city_mun || []) {
  const provKey = provinceByCode.get(c.prov_code) || metroManilaKey;
  if (!provKey) continue;
  const name = formatName(c.name);
  cities.push({ key: `c-${c.psgc_code}`, provinceKey: provKey, name, code: c.mun_code });
}

// Add "Manila" as a city for Metro Manila (for venue selection)
if (metroManilaKey && !cities.some((x) => x.provinceKey === metroManilaKey && x.name === "Manila")) {
  cities.unshift({
    key: "c-manila-city",
    provinceKey: metroManilaKey,
    name: "Manila",
    code: "133900",
  });
}

function formatName(s) {
  if (!s || typeof s !== "string") return "";
  return s
    .replace(/\s*\/\s*/g, " / ")
    .replace(/\b\w/g, (c) => c.toUpperCase())
    .replace(/\b(Ii|Iii|Iv|Vi)\b/gi, (m) => m.toUpperCase())
    .trim();
}

// Generate SQL with fixed UUIDs for reproducibility
const crypto = require("crypto");
function uuidFromSeed(seed) {
  const hash = crypto.createHash("sha256").update(seed).digest("hex");
  return `${hash.slice(0, 8)}-${hash.slice(8, 12)}-4${hash.slice(13, 16)}-a${hash.slice(17, 20)}-${hash.slice(20, 32)}`;
}

const provinceUuids = new Map(); // key -> uuid

let sql = `-- Philippine provinces and cities (generated by npm run generate:psgc-seed)
-- Source: philippine-location-json-for-geer

`;

// Provinces
sql += `INSERT INTO public.provinces (id, name, code) VALUES\n`;
sql += provinces
  .map((p) => {
    const uid = uuidFromSeed("prov-" + (p.code || p.key));
    provinceUuids.set(p.key, uid);
    return `  ('${uid}'::uuid, '${escapeSql(p.name)}', ${p.code ? `'${p.code}'` : "NULL"})`;
  })
  .join(",\n");
sql += "\nON CONFLICT (id) DO NOTHING;\n\n";

// Cities
sql += `INSERT INTO public.cities (id, province_id, name, code) VALUES\n`;
const cityRows = cities.map((c) => {
  const uid = uuidFromSeed("city-" + (c.code || c.key));
  const provUid = provinceUuids.get(c.provinceKey);
  if (!provUid) throw new Error("Missing province for city: " + c.name);
  return `  ('${uid}'::uuid, '${provUid}'::uuid, '${escapeSql(c.name)}', ${c.code ? `'${c.code}'` : "NULL"})`;
});
sql += cityRows.join(",\n");
sql += "\nON CONFLICT (id) DO NOTHING;\n";

function escapeSql(s) {
  return String(s).replace(/'/g, "''");
}

fs.writeFileSync(OUT_PATH, sql, "utf8");
console.log(`Wrote ${OUT_PATH} (${provinces.length} provinces, ${cities.length} cities)`);
